#pragma once

#include <cstdint>
#include <cstddef>
#include <cstring>
#include <memory>
#include <random>
#include <span>

namespace lifted::verification
{
    // Constraints that can be applied to generated 64-bit values.
    // alignment must be a power of 2 (1 = no alignment).
    // Aligns down first, then maps into [min, max] via modulo.
    // Note: if min is not a multiple of alignment, the result respects alignment
    // but may not lie exactly at min.
    struct value_constraints_t
    {
        uint64_t min = 0;
        uint64_t max = UINT64_MAX;
        uint8_t alignment = 1; // power of 2; 1 = unconstrained
    };

    // Abstract value generator — owns its seed/state, produces raw bytes or typed values.
    //
    // Override fill_buffer() as the primary generation method; the default generate*()
    // methods delegate to it.  All methods return raw generated bytes — constraint
    // application (alignment, range, etc.) is the responsibility of derived classes.
    //
    // Instances are created by value_generator_factory::create(seed) and owned by the caller.
    struct value_generator
    {
        virtual ~value_generator() = default;

        // Primary override point.  Fill buf with generated bytes using internal state.
        virtual void fill_buffer(std::span<std::byte> buf) = 0;

        // Typed accessors — by default call fill_buffer and return raw bytes.
        virtual uint8_t generate8()
        {
            uint8_t v;
            fill_buffer(std::span{reinterpret_cast<std::byte *>(&v), 1});
            return v;
        }

        virtual uint16_t generate16()
        {
            uint16_t v;
            fill_buffer(std::span{reinterpret_cast<std::byte *>(&v), 2});
            return v;
        }

        virtual uint32_t generate32()
        {
            uint32_t v;
            fill_buffer(std::span{reinterpret_cast<std::byte *>(&v), 4});
            return v;
        }

        virtual uint64_t generate64()
        {
            uint64_t v;
            fill_buffer(std::span{reinterpret_cast<std::byte *>(&v), 8});
            return v;
        }
    };

    // Factory that produces seeded value_generator instances.
    // Stored as a non-owning pointer in run_params_t / paged_memory_state,
    // mirroring the sentinel_oracle pattern.
    struct value_generator_factory
    {
        virtual ~value_generator_factory() = default;
        virtual std::unique_ptr<value_generator> create(uint64_t seed) const = 0;
    };

    // ── Default implementations ───────────────────────────────────────────────

    // Generator backed by std::mt19937_64.
    // Constraints (alignment + range) are applied per 8-byte chunk inside fill_buffer,
    // so generate64() and page fills are both naturally constrained.
    struct uniform_value_generator : value_generator
    {
        value_constraints_t constraints;

        explicit uniform_value_generator(uint64_t seed) : rng_(seed) {}
        uniform_value_generator(uint64_t seed, value_constraints_t c) : constraints(c), rng_(seed) {}

        void fill_buffer(std::span<std::byte> buf) override
        {
            size_t i = 0;
            while (i + 8 <= buf.size())
            {
                uint64_t v = apply_constraints(rng_());
                std::memcpy(buf.data() + i, &v, 8);
                i += 8;
            }
            if (i < buf.size())
            {
                uint64_t v = apply_constraints(rng_());
                std::memcpy(buf.data() + i, &v, buf.size() - i);
            }
        }

    private:
        std::mt19937_64 rng_;

        uint64_t apply_constraints(uint64_t v) const
        {
            if (constraints.alignment > 1)
                v &= ~(uint64_t)(constraints.alignment - 1);

            if (constraints.min != 0 || constraints.max != UINT64_MAX)
            {
                uint64_t span = constraints.max - constraints.min + 1;
                if (span != 0)
                    v = constraints.min + (v % span);
            }

            return v;
        }
    };

    // Factory that builds uniform_value_generator instances with a fixed constraints set.
    struct uniform_value_generator_factory : value_generator_factory
    {
        value_constraints_t constraints;

        uniform_value_generator_factory() = default;
        explicit uniform_value_generator_factory(value_constraints_t c) : constraints(c) {}

        std::unique_ptr<value_generator> create(uint64_t seed) const override
        {
            return std::make_unique<uniform_value_generator>(seed, constraints);
        }
    };

} // namespace lifted::verification
